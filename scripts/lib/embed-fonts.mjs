/*
  Regenerates scripts/lib/brand-fonts.mjs from brand/fonts/subset.

    node scripts/lib/embed-fonts.mjs

  Run scripts/lib/subset-fonts.sh first if a font file in the brand kit changes.
*/
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const FILES = [
  ["switzerRegular", "Switzer-Regular.ttf"],
  ["switzerMedium", "Switzer-Medium.ttf"],
  ["switzerSemiBold", "Switzer-SemiBold.ttf"],
];

const body = FILES.map(([name, file]) => {
  const data = readFileSync(join("brand/fonts/subset", file)).toString("base64");
  return `  ${name}: {\n    file: "${file}",\n    data:\n      "${data}",\n  },`;
}).join("\n");

writeFileSync(
  "scripts/lib/brand-fonts.mjs",
  `/*\n  The brand fonts, embedded so document builds need no network and stay\n` +
    `  reproducible. Files come from brand/fonts, self-hosted from Fontshare at the\n` +
    `  three weights these documents use.\n\n` +
    `  Generated by scripts/lib/embed-fonts.mjs - do not edit by hand.\n*/\n\n` +
    `export const FONTS = {\n${body}\n};\n`,
);
console.log("brand-fonts.mjs rebuilt");
